import { sharedAchievementDefinitions } from '@/lib/achievements';
import {
  createSnapshotLessonContentProvider,
  lessonEvaluatorContractVersion,
  type CourseSeed,
} from '@/lib/domain';

import {
  validateProgrammeDefinition,
  type ProgrammeDefinition,
} from '../definition';
import manifest from './content/manifest.json';
import moduleOne from './content/s1-m01.json';
import moduleTwo from './content/s1-m02.json';
import { programvareutviklingLessonCopy } from './lessonCopy';
import { programvareutviklingTerminology } from './terminology';

/**
 * Programvareutvikling (Epic E): the first real additional programme,
 * delivering the authored M01/M02 slice. The catalogue maps the two modules
 * to `module` units and the 25 missions to `lesson` items, from the
 * committed content snapshot (generated by
 * `scripts/programvareutvikling-content.mjs` from `pilot.json` at its
 * recorded SHA-256). The lesson bodies, exercises, hints, feedback and
 * evaluator specifications stay behind the asynchronous content provider.
 *
 * Identity follows the CS50 convention: the definition key equals the
 * catalogue identity, and the persisted programme ID is stable. Registration
 * is not enrolment.
 */

const catalogueId = 'programvareutvikling-2026';

/**
 * The catalogue, derived from the snapshot manifest. Lowercased mission IDs
 * are the durable item IDs. An optional reinforcement mission shows the
 * length the authors show for it (its optional minutes); module length
 * excludes it by policy (DC-07).
 */
const catalogue: CourseSeed = {
  courseId: catalogueId,
  title: 'Programvareutvikling',
  dataVersion: manifest.contentVersion,
  // The date the authoritative source was verified for this export (E0).
  sourceCheckedDate: '2026-10-03',
  units: manifest.modules.map((module) => ({
    id: module.catalogueUnitId,
    order: module.order,
    title: module.title,
    type: 'module' as const,
    // The programme as the source pensum list names it: 2026–2028.
    sourceYear: 2026,
    required: true,
    items: module.missions.map((mission) => ({
      id: mission.itemId,
      type: 'lesson' as const,
      title: mission.title,
      required: !mission.optional,
      estimatedMinutes:
        mission.surface === 'reinforcement'
          ? ((mission as { optionalMinutes?: number }).optionalMinutes ??
            mission.minutes)
          : mission.minutes,
      order: mission.order,
    })),
  })),
};

const lessons = createSnapshotLessonContentProvider({
  manifest,
  modules: {
    'S1-M01': () => moduleOne,
    'S1-M02': () => moduleTwo,
  },
  evaluatorContractVersion: lessonEvaluatorContractVersion,
  copy: programvareutviklingLessonCopy,
});

export const programvareutviklingDefinition: ProgrammeDefinition =
  validateProgrammeDefinition({
    definitionKey: catalogueId,
    catalogueId,
    programmeId: 'programvareutvikling',
    title: 'Programvareutvikling',
    catalogue,
    policy: {
      catalogueRules: {
        requiredUnitTypes: [],
        optionalItemsInUnitLength: false,
      },
      // The minimum neutral valid policy: the source defines no XP economy,
      // and nothing is awarded for opening, reading or marking a lesson.
      xp: {
        completionAwards: [],
        statusMilestones: [],
        unitCompletionBonuses: [],
        itemMilestones: [],
      },
      workflow: { sequenceItemTypes: [], correctionItemTypes: [] },
      achievements: sharedAchievementDefinitions,
    },
    content: {
      language: 'nb',
      externalResources: {
        allowedUrlPrefixes: [],
        unitLinks: {},
        itemLinks: {},
      },
      studyGuides: { unitGuides: {}, itemGuides: {} },
      terminology: programvareutviklingTerminology,
      lessons,
    },
  });
