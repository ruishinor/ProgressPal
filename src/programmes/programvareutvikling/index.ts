import { loadSameOriginText } from '@/lib/assets';
import {
  createContentAssetProvider,
  lessonEvaluatorContractVersion,
  parseProgrammeContentCatalogue,
  type CourseSeed,
} from '@/lib/domain';

import {
  validateProgrammeDefinition,
  type ProgrammeDefinition,
} from '../definition';
import { programvareutviklingAchievements } from './achievements';
import catalogueJson from './content/catalogue.json';
import { programvareutviklingLessonCopy } from './lessonCopy';
import { programvareutviklingMicrolearning } from './microlearning';
import {
  programvareutviklingDisplayName,
  programvareutviklingTerminology,
} from './terminology';

/**
 * Programvareutvikling (Epic E): the first real additional programme,
 * delivering the authored M01/M02 slice. The catalogue maps the two modules
 * to `module` units and the 25 missions to `lesson` items, from the
 * bundled content catalogue (generated by
 * `scripts/programvareutvikling-content.mjs` from `pilot.json` at its
 * recorded SHA-256). The lesson bodies, exercises, hints, feedback and
 * evaluator specifications are versioned same-origin content assets outside
 * the application bundle, loaded and verified by the content provider.
 *
 * Identity follows the CS50 convention: the definition key equals the
 * catalogue identity, and the persisted programme ID is stable. Registration
 * is not enrolment.
 */

const catalogueId = 'programvareutvikling-2026';
const content = parseProgrammeContentCatalogue(catalogueJson);

/**
 * The catalogue, derived from the bundled content catalogue. Lowercased mission IDs
 * are the durable item IDs. An optional reinforcement mission shows the
 * length the authors show for it (its optional minutes); module length
 * excludes it by policy (DC-07).
 */
const catalogue: CourseSeed = {
  courseId: catalogueId,
  title: 'Programvareutvikling',
  dataVersion: content.contentVersion,
  // The date the authoritative source was verified for this export (E0).
  sourceCheckedDate: '2026-10-03',
  units: content.modules.map((module) => ({
    id: module.catalogueUnitId,
    order: module.order,
    title: module.title,
    type: 'module' as const,
    // The programme as the source pensum list names it: 2026–2028.
    sourceYear: 2026,
    required: true,
    items: module.missions.map((mission) => ({
      id: mission.itemId,
      type: 'lesson' as const,
      title: mission.title,
      required: !mission.optional,
      estimatedMinutes:
        mission.surface === 'reinforcement'
          ? (mission.optionalMinutes ?? mission.minutes)
          : mission.minutes,
      order: mission.order,
    })),
  })),
};

const lessons = createContentAssetProvider({
  catalogue: content,
  loadText: loadSameOriginText,
  evaluatorContractVersion: lessonEvaluatorContractVersion,
  copy: programvareutviklingLessonCopy,
  // Owner decision 2026-10-10: Task 6 of S1-M01 (the ten steps from problem
  // to presentation) may be checked twice while it is built. Content and
  // every other task are unchanged.
  progressCheckSubjectIds: ['s1-m01-p05-e06'],
});

export const programvareutviklingDefinition: ProgrammeDefinition =
  validateProgrammeDefinition({
    definitionKey: catalogueId,
    catalogueId,
    programmeId: 'programvareutvikling',
    title: programvareutviklingDisplayName,
    catalogue,
    policy: {
      catalogueRules: {
        requiredUnitTypes: [],
        optionalItemsInUnitLength: false,
      },
      // Nothing is awarded for opening, reading or marking a lesson: the
      // catalogue-progress economy stays empty.
      xp: {
        completionAwards: [],
        statusMilestones: [],
        unitCompletionBonuses: [],
        itemMilestones: [],
      },
      // Lesson XP (owner decision 2026-10-03; E-SCHEMA-1A): only correct
      // work earns, in this programme's own ledger, and the same task earns
      // the same at every level. Repeats, reloads and hints add nothing.
      //
      // Effort rubric (owner decisions 2026-10-10 and 2026-10-11, simulated in
      // tests/programmes/xpCalibration.test.ts): the family values are the
      // standard tier. A choice task (one click among options) earns 2 less;
      // writing or changing a program, diagnosing an error (type, line and
      // cause), tracing values line by line and designing tests earn 5 more,
      // as does Task 6 (ordering the ten steps of the development process).
      // Authored guided/independent adds nothing: every independent task is
      // already a program or a test table. A choice task earns 6, a standard
      // task 8 and a demanding one 13 in a lesson; practical work (lab and
      // quest) 12, 14 and 19. Bonuses (a finished lesson, a cleared module
      // checkpoint, a finished module) stay below a fifth of all XP.
      lessonXp: {
        solved: {
          formative: 8,
          practical: 14,
          retrieval: 11,
          checkpoint: 12,
          optional: 3,
        },
        authoredMilestone: 10,
        independentRecall: 4,
        lessonCompleted: 12,
        checkpointCleared: 60,
        moduleCompleted: 30,
        effort: {
          introductory: { adjust: -2, responseModes: ['mcq'] },
          complex: {
            adjust: 5,
            responseModes: ['program', 'diagnose', 'trace', 'testtable'],
            subjectIds: ['s1-m01-p05-e06'],
          },
        },
        reasons: {
          solved: 'Løste en oppgave i «{lesson}»',
          authoredMilestone: 'Nådde et delmål i «{lesson}»',
          independentRecall: 'Husket svaret uten hjelp i «{lesson}»',
          lessonCompleted: 'Fullførte «{lesson}»',
          checkpointCleared: 'Besto modulsjekken i «{module}»',
          moduleCompleted: 'Fullførte modulen «{module}»',
        },
      },
      // Level curve (owner decisions 2026-10-10, 2026-10-11): 55 XP for
      // level 2, then 20 more for each next level (55, 75, 95, ...). About
      // five solved tasks reach level 2, then roughly 9, 10, 17, 16 more;
      // later levels take gradually longer. CS50x keeps the shared curve.
      levelCurve: { firstLevelXp: 55, levelStepXp: 20 },
      workflow: { sequenceItemTypes: [], correctionItemTypes: [] },
      achievements: programvareutviklingAchievements,
    },
    content: {
      language: 'nb',
      externalResources: {
        allowedUrlPrefixes: [],
        unitLinks: {},
        itemLinks: {},
      },
      studyGuides: { unitGuides: {}, itemGuides: {} },
      terminology: programvareutviklingTerminology,
      lessons,
      microlearning: programvareutviklingMicrolearning,
    },
  });
